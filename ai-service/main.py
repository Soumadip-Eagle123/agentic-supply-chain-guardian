@asynccontextmanager
async def lifespan(app: FastAPI):
    """Executes on service startup to seed baseline handbook documents."""
    default_pdf_path = "/app/data/defaults/global_SOP.pdf"
    if os.path.exists(default_pdf_path):
        print("[BOOT]: Baseline corporate handbook detected. Generating embedding vectors...")
        try:
            chunks_indexed = rag_engine.process_and_index_pdf(
                file_path=default_pdf_path,
                collection_name="supply_chain_defaults",
                origin_name="global_SOP.pdf"
            )
            print(f"[BOOT]: Indexed {chunks_indexed} default SOP chunks.")
        except Exception as e:
            print(f"[BOOT ERROR]: Error while seeding default collection: {e}")
    else:
        print("[BOOT WARN]: Missing default PDF at /app/data/defaults/global_SOP.pdf. Skipping seeding.")
    yield

